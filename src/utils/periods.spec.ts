import { buildPeriod } from './periods';

describe('buildPeriod', () => {
  it.each([
    [
      'MONTHLY',
      '2026-07-14T12:00:00+07:00',
      '2026-06-14T17:00:00.000Z',
      '2026-07-14T16:59:59.999Z',
      2026,
      7,
    ],
    [
      'MONTHLY',
      '2026-07-15T00:00:00+07:00',
      '2026-07-14T17:00:00.000Z',
      '2026-08-14T16:59:59.999Z',
      2026,
      8,
    ],
    [
      'MONTHLY',
      '2026-12-15T00:00:00+07:00',
      '2026-12-14T17:00:00.000Z',
      '2027-01-14T16:59:59.999Z',
      2027,
      1,
    ],
    [
      'QUARTERLY',
      '2026-03-14T12:00:00+07:00',
      '2025-12-14T17:00:00.000Z',
      '2026-03-14T16:59:59.999Z',
      2026,
      1,
    ],
    [
      'QUARTERLY',
      '2026-03-15T00:00:00+07:00',
      '2026-03-14T17:00:00.000Z',
      '2026-06-14T16:59:59.999Z',
      2026,
      2,
    ],
    [
      'QUARTERLY',
      '2026-09-15T00:00:00+07:00',
      '2026-09-14T17:00:00.000Z',
      '2026-12-14T16:59:59.999Z',
      2026,
      4,
    ],
    [
      'SEMI_ANNUAL',
      '2026-06-14T12:00:00+07:00',
      '2025-12-14T17:00:00.000Z',
      '2026-06-14T16:59:59.999Z',
      2026,
      1,
    ],
    [
      'SEMI_ANNUAL',
      '2026-06-15T00:00:00+07:00',
      '2026-06-14T17:00:00.000Z',
      '2026-12-14T16:59:59.999Z',
      2026,
      2,
    ],
    [
      'SEMI_ANNUAL',
      '2026-12-15T00:00:00+07:00',
      '2026-12-14T17:00:00.000Z',
      '2027-06-14T16:59:59.999Z',
      2027,
      1,
    ],
    [
      'ANNUAL',
      '2026-12-14T12:00:00+07:00',
      '2025-12-14T17:00:00.000Z',
      '2026-12-14T16:59:59.999Z',
      2026,
      1,
    ],
    [
      'ANNUAL',
      '2026-12-15T00:00:00+07:00',
      '2026-12-14T17:00:00.000Z',
      '2027-12-14T16:59:59.999Z',
      2027,
      1,
    ],
  ] as const)(
    '%s uses the correct boundary and sequence for %s',
    (frequency, anchor, periodStartAt, dueAt, year, sequence) => {
      const period = buildPeriod(frequency, new Date(anchor));

      expect(period).toMatchObject({ year, sequence });
      expect(period.periodStartAt.toISOString()).toBe(periodStartAt);
      expect(period.dueAt.toISOString()).toBe(dueAt);
    },
  );
});
